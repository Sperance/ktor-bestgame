package application.enums

/**
 * Что именно выставлено на аукционе.
 *
 * Предметы в игре двух видов и хранятся по-разному, поэтому и лоты
 * различаются: у экипировки свой документ с зароленными модификаторами,
 * у простых предметов - только ссылка на справочник и количество.
 */
enum class EnumAuctionLotKind {

    /**
     * Экземпляр экипировки. На время торгов лежит внутри лота.
     */
    EQUIPMENT,

    /**
     * Стакающийся предмет из справочника `Items`, в том числе сферы.
     */
    ITEM
}
