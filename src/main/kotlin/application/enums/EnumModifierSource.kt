package application.enums

enum class EnumModifierSource {

    /**
     * Встроенный модификатор базового предмета.
     */
    IMPLICIT,

    /**
     * Префикс редкого предмета.
     */
    PREFIX,

    /**
     * Суффикс редкого предмета.
     */
    SUFFIX,

    /**
     * Уникальный модификатор.
     */
    UNIQUE,

    /**
     * Модификация через enchant.
     */
    ENCHANTMENT,

    /**
     * Особая модификация предмета.
     */
    CORRUPTION,

    /**
     * Бонус узла дерева навыков.
     *
     * На предметах не появляется и не роллится: значения задаёт сам узел.
     */
    PASSIVE,

    /**
     * Ручная работа (с 0.38.0): её ставит кузнец (или картограф на карту) сверх префиксов и
     * суффиксов, места аффикса она не занимает, и ни одна сфера её не трогает.
     */
    HANDCRAFTED,

    /**
     * Алхимическая строка карты (с 0.38.0): её добавляют сферы алхимика, до трёх на карте и без
     * повторов; обычные сферы её не трогают.
     */
    ALCHEMY,
    /**
     * Модификатор монстра (с 0.66.0): та же схема, что у предметов, - эффекты и тиры по уровню карты, -
     * только носит его монстр кампании, а не предмет. На предметах не появляется и сферами не катается.
     */
    MONSTER,
    /**
     * Строка особой эссенции (с 0.69.0): её ставит только эссенция - Безумия, Кошмара, Бреда или
     * Истерии. Места аффикса она не занимает, но уходит вместе с аффиксами под перекатом и очищением.
     */
    ESSENCE,
}