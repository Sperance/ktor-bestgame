package application.enums

/**
 * Состояние лота на аукционе.
 *
 * Закрытые лоты не удаляются: по ним видно историю торгов.
 */
enum class EnumAuctionLotStatus {

    /**
     * Лот на витрине, товар лежит в нём и ждёт покупателя.
     */
    ACTIVE,

    /**
     * Лот продан: товар ушёл покупателю, сферы - продавцу.
     */
    SOLD,

    /**
     * Продавец снял лот и забрал товар обратно.
     */
    CANCELLED
}
