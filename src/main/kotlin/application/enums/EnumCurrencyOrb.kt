package application.enums

/**
 * Валютные сферы POE, реализованные на сервере.
 *
 * Сами предметы лежат в коллекции `Items` с категорией [CATEGORY] и
 * подкатегорией, равной имени элемента этого перечисления. Перечисление -
 * это связка документа с его поведением: у каждой сферы своя ветка
 * в CurrencyApplier, поэтому чисто данными, как модификаторы, она быть не может.
 *
 * Сферы POE, которых здесь нет, завязаны на механики, которых нет в проекте:
 * сокеты и связи (Jeweller's, Fusing, Chromatic), качество (Whetstone, Scrap,
 * Bauble), карты и крафт на верстаке. Дерево пассивок появилось, поэтому
 * [ORB_OF_REGRET] здесь есть - но тратит её дерево, а не CurrencyApplier.
 */
enum class EnumCurrencyOrb {

    /**
     * Обычный предмет становится магическим и получает аффиксы.
     */
    ORB_OF_TRANSMUTATION,

    /**
     * Добавляет магическому предмету ещё один аффикс.
     */
    ORB_OF_AUGMENTATION,

    /**
     * Перекатывает аффиксы магического предмета.
     */
    ORB_OF_ALTERATION,

    /**
     * Обычный предмет становится редким и получает аффиксы.
     */
    ORB_OF_ALCHEMY,

    /**
     * Магический предмет становится редким, сохраняя аффиксы и получая ещё один.
     */
    REGAL_ORB,

    /**
     * Перекатывает аффиксы редкого предмета.
     */
    CHAOS_ORB,

    /**
     * Добавляет редкому предмету ещё один аффикс.
     */
    EXALTED_ORB,

    /**
     * Перекатывает значения аффиксов, сохраняя сами аффиксы и их тиры.
     */
    DIVINE_ORB,

    /**
     * Убирает с предмета случайный аффикс.
     */
    ORB_OF_ANNULMENT,

    /**
     * Снимает с предмета все аффиксы и возвращает его к обычной редкости.
     */
    ORB_OF_SCOURING,

    /**
     * Перекатывает значения implicit-модификаторов.
     */
    BLESSED_ORB,

    /**
     * Портит предмет: вешает модификатор порчи, после чего предмет неизменяем.
     */
    VAAL_ORB,

    /**
     * Делает из обычного предмета предмет случайной редкости,
     * с небольшим шансом - уникальный того же слота.
     */
    ORB_OF_CHANCE,

    /**
     * Создаёт копию предмета. Как в POE, копия неизменяема.
     */
    MIRROR_OF_KALANDRA,

    /**
     * Закрепляет случайный аффикс редкого предмета, у которого их не меньше четырёх.
     * Закреплённый аффикс не трогает больше ни одна сфера.
     */
    FRACTURING_ORB,

    /**
     * Накладывает на редкий предмет влияние Создателя и добавляет модификатор из его пула.
     */
    SHAPERS_ORB,

    /**
     * Накладывает на редкий предмет влияние Древнего и добавляет модификатор из его пула.
     */
    ELDER_ORB,

    /**
     * Сфера сожаления: возвращает один взятый узел дерева навыков.
     *
     * Единственная сфера, которая тратится не на предмет, а на персонажа,
     * поэтому её ветки в CurrencyApplier нет - её списывает дерево навыков.
     */
    ORB_OF_REGRET;

    companion object {
        /**
         * Категория, по которой сферы отличаются от прочих предметов в `Items`.
         */
        const val CATEGORY = "CURRENCY"

        /**
         * Сфера по подкатегории предмета или null, если предмет не сфера.
         */
        fun byCode(code: String): EnumCurrencyOrb? = entries.find { it.name == code }
    }
}
