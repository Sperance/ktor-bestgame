package application.enums

/**
 * Валютные сферы POE, реализованные на сервере.
 *
 * Сами предметы лежат в коллекции `Items` с категорией [CATEGORY] и
 * подкатегорией, равной имени элемента этого перечисления. Перечисление -
 * это связка документа с его поведением: у каждой сферы своя ветка
 * в CurrencyApplier, поэтому чисто данными, как модификаторы, она быть не может.
 *
 * Сферы POE, которых здесь нет, завязаны на механики, которых нет в проекте:
 * сокеты и связи (Jeweller's, Fusing, Chromatic) и качество снаряжения (Whetstone, Scrap);
 * качество фляги с 0.69.0 даёт «Стеклодув». Дерево пассивок появилось, поэтому
 * [ORB_OF_REGRET] здесь есть - но тратит её дерево, а не CurrencyApplier.
 */
enum class EnumCurrencyOrb {

    /**
     * Обычный предмет становится магическим и получает аффиксы.
     */
    ORB_OF_TRANSMUTATION,

    /**
     * Добавляет магическому предмету ещё один аффикс.
     */
    ORB_OF_AUGMENTATION,

    /**
     * Перекатывает аффиксы магического предмета.
     */
    ORB_OF_ALTERATION,

    /**
     * Обычный предмет становится редким и получает аффиксы.
     */
    ORB_OF_ALCHEMY,

    /**
     * Магический предмет становится редким, сохраняя аффиксы и получая ещё один.
     */
    REGAL_ORB,

    /**
     * Перекатывает аффиксы редкого предмета.
     */
    CHAOS_ORB,

    /**
     * Добавляет редкому предмету ещё один аффикс.
     */
    EXALTED_ORB,

    /**
     * Перекатывает значения аффиксов, сохраняя сами аффиксы и их тиры.
     */
    DIVINE_ORB,

    /**
     * Убирает с предмета случайный аффикс.
     */
    ORB_OF_ANNULMENT,

    /**
     * Снимает с предмета все аффиксы и возвращает его к обычной редкости.
     */
    ORB_OF_SCOURING,

    /**
     * Перекатывает значения implicit-модификаторов.
     */
    BLESSED_ORB,

    /**
     * Портит предмет: вешает модификатор порчи, после чего предмет неизменяем.
     */
    VAAL_ORB,

    /**
     * Делает из обычного предмета предмет случайной редкости,
     * с небольшим шансом - уникальный того же слота.
     */
    ORB_OF_CHANCE,

    /**
     * Создаёт копию предмета. Как в POE, копия неизменяема.
     */
    MIRROR_OF_KALANDRA,

    /**
     * Закрепляет случайный аффикс редкого предмета, у которого их не меньше четырёх.
     * Закреплённый аффикс не трогает больше ни одна сфера.
     */
    FRACTURING_ORB,

    /**
     * Накладывает на редкий предмет влияние Создателя и добавляет модификатор из его пула.
     */
    SHAPERS_ORB,

    /**
     * Накладывает на редкий предмет влияние Древнего и добавляет модификатор из его пула.
     */
    ELDER_ORB,

    /**
     * Сфера сожаления: возвращает один взятый узел дерева навыков.
     *
     * Единственная сфера, которая тратится не на предмет, а на персонажа,
     * поэтому её ветки в CurrencyApplier нет - её списывает дерево навыков.
     */
    ORB_OF_REGRET,

    // ---------- Сферы алхимика для карт (с 0.38.0): применяются только к картам ----------

    /** Поднимает каждый аффикс карты на тир выше. */
    EMPOWERING_ORB,

    /** Снимает с карты случайный вредный аффикс - и его награду. */
    MERCY_ORB,

    /** Добавляет карте вредный аффикс сверх лимита. */
    PERIL_ORB,

    /** Строка «Алхимия»: больше монстров. */
    HORDE_ORB,

    /** Строка «Алхимия»: больше магических монстров. */
    MAGUS_ORB,

    /** Строка «Алхимия»: больше редких монстров. */
    ELITE_ORB,

    /** Строка «Алхимия»: больше добычи. */
    BOUNTY_ORB,

    /** Строка «Алхимия» (0.66.0): больше сундуков. */
    TREASURE_ORB,

    /** Строка «Алхимия» (0.66.0): больше золота. */
    GILDED_ORB,

    /** Строка «Алхимия» (0.66.0): босс сильнее и щедрее. */
    WARDEN_ORB,

    /** Строка «Алхимия» (0.69.0): «Сфера Сущности» - лишние кристаллы эссенций на карте. */
    ESSENCE_ORB,

    /** Строка «Алхимия» (0.69.0): «Сфера Писца» - книги умений чаще. */
    SCRIBE_ORB,

    /** «Стеклодув» (0.69.0): качество фляги - два процента обычной, один волшебной, до двадцати. */
    GLASSBLOWERS_BAUBLE,

    // ---------- Свитки зачарователя (0.66.0): зачарование своего слота, одно на предмет ----------

    /** Зачарование шлема. */
    HELMET_SCROLL,

    /** Зачарование перчаток. */
    GLOVES_SCROLL,

    /** Зачарование сапог. */
    BOOTS_SCROLL,

    /** Зачарование оружия. */
    WEAPON_SCROLL;

    val mapOnly: Boolean get() = ordinal >= EMPOWERING_ORB.ordinal && ordinal <= SCRIBE_ORB.ordinal

    /** Сфера только для фляг (0.69.0). */
    val flaskOnly: Boolean get() = this == GLASSBLOWERS_BAUBLE

    /** Свиток зачарователя: ложится на снаряжение своего слота, см. CurrencyApplier. */
    val enchant: Boolean get() = ordinal >= HELMET_SCROLL.ordinal

    /** Слот, который зачаровывает свиток; у прочих сфер - null. */
    val enchantSlot: String? get() = when (this) {
        HELMET_SCROLL -> "helmet"
        GLOVES_SCROLL -> "gloves"
        BOOTS_SCROLL -> "boots"
        WEAPON_SCROLL -> "weapon"
        else -> null
    }

    companion object {
        /**
         * Категория, по которой сферы отличаются от прочих предметов в `Items`.
         */
        const val CATEGORY = "CURRENCY"

        /**
         * Сфера по подкатегории предмета или null, если предмет не сфера.
         */
        private val byName: Map<String, EnumCurrencyOrb> = entries.associateBy { it.name }

        fun byCode(code: String): EnumCurrencyOrb? = byName[code]
    }
}
