package application.enums

/**
 * Редкость предмета. Определяет, сколько аффиксов предмет может нести.
 *
 * Лестница построена как в POE: обычный предмет аффиксов не имеет,
 * магический держит по одному префиксу и суффиксу, редкий - по три.
 * EPIC и MYTHICAL - надстройка этого проекта над лестницей POE,
 * UNIQUE аффиксов не роллит вовсе: его модификаторы закреплены самим предметом.
 */
enum class EnumRarity(
    /**
     * Сколько префиксов предмет этой редкости может нести.
     */
    val prefixCount: Int,

    /**
     * Сколько суффиксов предмет этой редкости может нести.
     */
    val suffixCount: Int
) {
    COMMON(0, 0),
    UNCOMMON(1, 1),
    RARE(3, 3),
    EPIC(4, 3),
    UNIQUE(0, 0),
    MYTHICAL(4, 4);

    /**
     * Сколько всего аффиксов помещается на предмет этой редкости.
     */
    fun affixCount(): Int = prefixCount + suffixCount
}
