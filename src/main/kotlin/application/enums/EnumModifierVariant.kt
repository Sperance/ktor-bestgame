package application.enums

/**
 * Вариант описания модификатора (0.66.0): одна запись семейства в `modifiers.json` рождает
 * несколько описаний с одними эффектами и текстом, но разными кодами, тирами и правилами.
 *
 * Код варианта - `<семейство>@<вариант>`; природный вариант носит код семейства как есть.
 * Так «+# к здоровью» на предмете, его локальная копия внутри предмета, верстачная строка,
 * имплисит базы и порченый имплисит - одно семейство, а не пять описаний с пятью переводами.
 */
enum class EnumModifierVariant(val suffix: String?) {
    /** Как записано: префикс, суффикс, имплисит, пассивка, модификатор монстра - источник семейства. */
    NATURAL(null),

    /** Локальная копия: считается внутри своего предмета, см. ModifierDefinition.isLocal. */
    LOCAL("LOCAL"),

    /** Верстачная копия: её ставит верстак, сферы не катают; группа - семейство. */
    CRAFTED("CRAFTED"),

    /** Имплисит базы с теми же эффектами. */
    IMPLICIT("IMPLICIT"),

    /** Порченый имплисит: его ставит Vaal Orb вместо имплисита базы. */
    CORRUPTED("CORRUPTED"),

    /** Зачарование: его ставит свиток зачарователя, одно на предмет. */
    ENCHANT("ENCHANT");

    companion object {
        const val SEPARATOR = "@"

        /** Код варианта семейства [family]. */
        fun code(family: String, variant: EnumModifierVariant): String =
            variant.suffix?.let { "$family$SEPARATOR$it" } ?: family

        /** Семейство по коду описания: всё до разделителя. */
        fun family(code: String): String = code.substringBefore(SEPARATOR)
    }
}
