package application.enums

/**
 * Вид узла дерева навыков, как в POE.
 */
enum class EnumSkillNodeType {

    /**
     * Стартовый узел класса. Бесплатен, с него начинается прокачка дерева.
     */
    START,

    /**
     * Малый узел: небольшой прирост характеристик.
     */
    SMALL,

    /**
     * Нотабль: заметный бонус, обычно завершает ветку малых узлов.
     */
    NOTABLE,

    /**
     * Кейстоун: меняет правила игры, часто вместе с серьёзным минусом.
     */
    KEYSTONE,

    /**
     * Гнездо под самоцвет. Собственных бонусов не имеет: всё, что оно даёт,
     * приносит вставленный самоцвет, и только пока само гнездо взято.
     */
    JEWEL_SOCKET
}
